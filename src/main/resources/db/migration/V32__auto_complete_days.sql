-- 배송완료 자동 처리 기준 일수.
--
-- 택배 추적 API 를 붙이지 않았으므로 실제 도착 시각을 알 수 없다. 그래서 발송 후
-- 이 기간이 지나면 "배송 완료"로 바꾼다. 화면 표시를 위한 추정값이다.
--
-- ★ 청약철회 기간은 법적으로 손님이 "실제로 물건을 받은 날"부터 센다.
--   여기서 찍는 날짜가 그 기산일을 대신하지 않는다 — 분쟁이 생기면 실제 수령일로 판단한다.
-- 0 이나 빈 값이면 자동 처리를 하지 않는다(관리자가 직접 바꾼다).
INSERT INTO site_setting (key, value, description) VALUES
    ('shipping.auto_complete_days', '3',
     '발송 후 며칠이 지나면 자동으로 배송 완료로 바꿀지. 0 으로 두면 자동으로 바꾸지 않고 직접 변경합니다.')
ON CONFLICT (key) DO NOTHING;

--
-- 지금 히어로는 «상품 1개 = 누끼 슬라이드 1개»(product.hero_*)라 상품이 아닌 이벤트·기획전
-- 이미지를 넣을 수 없었다. 이 표의 슬라이드는 사진 한 장이 히어로 화면 전체를 덮고,
-- 버튼을 누르면 정해 둔 주소로 간다. 메인 캐러셀이 누끼 슬라이드와 순서대로 섞어 돌린다.

CREATE TABLE hero_image_slide (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- PC 는 가로(16:9), 휴대폰은 세로(9:16)라 따로 받는다. 모바일을 비우면 PC 사진을 가운데 기준으로 잘라 쓴다.
    image_pc_key     VARCHAR(500)  NOT NULL,
    image_mobile_key VARCHAR(500),
    -- 화면에는 안 보이고 검색·화면 낭독기에 읽힌다. 접근성 필수.
    alt_text         VARCHAR(300)  NOT NULL,
    -- 버튼 문구·이동 주소가 둘 다 있을 때만 버튼이 나온다.
    button_label     VARCHAR(40),
    -- 사이트 안 주소(/로 시작) 또는 http(s) 주소만 (서버가 검증한다).
    link_url         VARCHAR(1000),
    open_new_tab     BOOLEAN       NOT NULL DEFAULT FALSE,
    -- 누끼 슬라이드(product.hero_sort)와 같은 숫자 공간에서 섞여 정렬된다.
    sort_order       INTEGER       NOT NULL DEFAULT 0,
    enabled          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_hero_image_slide_sort ON hero_image_slide (sort_order) WHERE enabled;
